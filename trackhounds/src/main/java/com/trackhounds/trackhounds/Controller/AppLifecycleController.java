package com.trackhounds.trackhounds.Controller;

import java.util.UUID;

import org.springframework.beans.factory.ObjectProvider;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.servlet.mvc.method.annotation.SseEmitter;

import com.trackhounds.trackhounds.Desktop.DesktopLauncher;

/**
 * Lets UI pages report their lifetime to the desktop launcher so the
 * application can exit when the last window is closed. In server-only mode
 * (no {@link DesktopLauncher}) the endpoints are inert.
 */
@RestController
@CrossOrigin("*")
@RequestMapping("/app")
public class AppLifecycleController {

    private final ObjectProvider<DesktopLauncher> launcher;

    public AppLifecycleController(ObjectProvider<DesktopLauncher> launcher) {
        this.launcher = launcher;
    }

    /**
     * Server-Sent Events stream that stays open while the page is alive.
     *
     * @param client identifier generated by the page
     * @return event stream, or {@code 204} in server-only mode (which tells the
     *         browser's {@code EventSource} not to reconnect)
     */
    @GetMapping(path = "/events", produces = MediaType.TEXT_EVENT_STREAM_VALUE)
    public ResponseEntity<SseEmitter> events(@RequestParam(name = "client", required = false) String client) {
        DesktopLauncher desktop = launcher.getIfAvailable();
        if (desktop == null) {
            return ResponseEntity.noContent().build();
        }
        String clientId = (client == null || client.isBlank()) ? UUID.randomUUID().toString() : client.trim();
        return ResponseEntity.ok(desktop.register(clientId));
    }

    /**
     * Beacon sent by a page when it unloads.
     *
     * @param client identifier generated by the page (request body, plain text)
     */
    @PostMapping("/window-closed")
    public ResponseEntity<Void> windowClosed(@RequestBody(required = false) String client) {
        DesktopLauncher desktop = launcher.getIfAvailable();
        if (desktop != null && client != null && !client.isBlank()) {
            desktop.windowClosed(client.trim());
        }
        return ResponseEntity.noContent().build();
    }
}
